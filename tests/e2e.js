const assert = require('node:assert/strict');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/history', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
  await page.route('**/api/user', route => route.fulfill({ status: 401, body: '{}' }));
  await page.route('**/api/search?**', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ results: [{ title: 'Vídeo E2E', url: 'https://example.com/video', thumbnail: '', duration: 90, site: 'Vimeo', uploader: 'Teste', kind: 'video' }], unavailableSources: [] }) }));
  await page.route('**/api/media/stream?**', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ url: 'https://example.com/video.mp4', title: 'Vídeo E2E', type: 'video', duration: 90 }) }));
  await page.route('**/api/downloads', async route => { if (route.request().method() === 'POST') { const payload = route.request().postDataJSON(); assert.equal(payload.format, 'webm'); assert.equal(payload.quality, '720'); await route.fulfill({ status: 202, contentType: 'application/json', body: JSON.stringify({ job: { id: 'e2e-job', title: 'Vídeo E2E', format: 'webm', status: 'queued', progress: { percent: 0, label: 'Na fila…' } } }) }); } else await route.continue(); });
  await page.goto('http://localhost:4173/', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('#searchResults').count(), 1);
  await page.locator('#searchQuery').fill('teste e2e');
  await page.locator('#searchForm').evaluate(form => form.requestSubmit());
  await page.locator('.search-result').waitFor();
  assert.equal(await page.locator('.search-result strong').textContent(), 'Vídeo E2E');
  await page.locator('[data-preview-type="video"]').click();
  await page.locator('#mediaStage').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#mediaVideo').getAttribute('src'), 'https://example.com/video.mp4');
  assert.equal(await page.locator('#playerContent').isVisible(), true);
  await page.locator('#quickFormat').selectOption('webm');
  await page.locator('#quickQuality').selectOption('720');
  await page.locator('#videoUrl').fill('https://example.com/video');
  await page.locator('#downloadButton').click();
  await page.locator('[data-live-job="e2e-job"]').waitFor();
  await page.locator('#closeStage').click();
  assert.equal(await page.locator('#mediaStage').isVisible(), false);
  await page.unroute('**/api/search?**');
  await page.route('**/api/search?**', route => route.fulfill({ status: 429, headers: { 'Retry-After': '7' }, contentType: 'application/json', body: JSON.stringify({ error: 'rate limited' }) }));
  await page.locator('#searchQuery').fill('limite');
  await page.locator('#searchForm').evaluate(form => form.requestSubmit());
  await page.locator('.rate-limit-card').waitFor();
  assert.match(await page.locator('.rate-limit-card').textContent(), /Limite temporário/);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('E2E OK: pesquisa, stream de vídeo, player grande, fechar player e HTTP 429.');
})().catch(error => { console.error(error); process.exit(1); });
